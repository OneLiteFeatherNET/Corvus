// Generates app/assets/css/m3-tokens.css: every Material 3 colour role (--md-sys-color-*) for the light and
// the dark scheme, from one seed colour. Run `pnpm tokens` after changing SEED; the test in
// m3-tokens.test.ts fails when the committed file is stale.
//
// Seed: OLF blue #114cc8 (the blue of the feather mark). Vibrant keeps the seed chroma, so the primary stays recognisably OLF blue (#0051df) while the
// surfaces stay calm; the roles reach WCAG AA (on-* roles are 4.5:1 or better by construction). The
// error role stays red and never collides with the primary hue, which a magenta seed would not guarantee.
// Success and warning are not part of M3; they are tonal palettes of the OLF green and yellow with the same
// tone mapping the standard roles use.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import {
  argbFromHex,
  Hct,
  hexFromArgb,
  MaterialDynamicColors,
  SchemeVibrant,
  TonalPalette,
} from '@material/material-color-utilities'

export const SEED = '#114cc8'
const GREEN = '#1bc755'
const YELLOW = '#f7cc2e'

const kebab = name => name.replace(/[A-Z]/g, c => `-${c.toLowerCase()}`)

// The roles of MaterialDynamicColors that are colours (the rest are helpers or palette key colours).
const ROLES = Object.getOwnPropertyNames(MaterialDynamicColors).filter(
  n => !/KeyColor$|^highestSurface$|^contentAccentToneDelta$/.test(n)
    && MaterialDynamicColors[n] && typeof MaterialDynamicColors[n].getArgb === 'function',
)

// Tones for [color, on-color, container, on-container].
const EXTRA = { light: [40, 100, 90, 10], dark: [80, 20, 30, 90] }

function scheme(dark) {
  const s = new SchemeVibrant(Hct.fromInt(argbFromHex(SEED)), dark, 0)
  const out = {}
  for (const role of ROLES) out[kebab(role)] = hexFromArgb(MaterialDynamicColors[role].getArgb(s))
  const tones = dark ? EXTRA.dark : EXTRA.light
  for (const [name, hex] of [['success', GREEN], ['warning', YELLOW]]) {
    const p = TonalPalette.fromInt(argbFromHex(hex))
    const [c, on, cont, onCont] = tones.map(t => hexFromArgb(p.tone(t)))
    out[name] = c
    out[`on-${name}`] = on
    out[`${name}-container`] = cont
    out[`on-${name}-container`] = onCont
  }
  return out
}

const block = (selector, vars, colorScheme, indent = '') =>
  `${indent}${selector} {\n${indent}  color-scheme: ${colorScheme};\n`
  + Object.entries(vars).map(([k, v]) => `${indent}  --md-sys-color-${k}: ${v};`).join('\n')
  + `\n${indent}}\n`

export function buildTokensCss() {
  const light = scheme(false)
  const dark = scheme(true)
  return `/* Generated by scripts/m3-tokens.mjs from seed ${SEED} (Vibrant). Do not edit; run \`pnpm tokens\`. */\n\n`
    + block(':root', light, 'light')
    + '\n/* Dark scheme: the system preference, unless the user picked a theme explicitly. */\n'
    + `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', dark, 'dark', '  ')}}\n\n`
    + block(':root[data-theme="dark"]', dark, 'dark')
    + '\n/* Tailwind utilities: bg-primary, text-on-surface, border-outline-variant, ... */\n'
    + `@theme inline {\n${Object.keys(light).map(k => `  --color-${k}: var(--md-sys-color-${k});`).join('\n')}\n}\n`
}

export const TOKENS_PATH = fileURLToPath(new URL('../app/assets/css/m3-tokens.css', import.meta.url))

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(TOKENS_PATH, buildTokensCss())
  console.log(`wrote ${TOKENS_PATH}`)
}
